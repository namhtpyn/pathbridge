// Multi-provider OIDC registry.
// Providers live in the settings table as one JSON blob (key `oidcProviders`);
// the legacy single-provider keys (oidcIssuer/oidcClientId/oidcClientSecret)
// migrate lazily into provider id `oidc` so existing linked accounts keep working.
import { v7 as uuidv7 } from 'uuid'
import { getSettings, setSetting } from '../settings/settings.service'

export interface OidcProvider {
  /** slug used as better-auth providerId; callback = /auth/callback/<id> */
  id: string
  /** human label shown on the login button */
  label: string
  issuer: string
  clientId: string
  /** never returned to the client; empty string allowed only in API responses */
  clientSecret: string
}

export type OidcProviderPublic = Omit<OidcProvider, 'clientSecret'> & { secretSet: boolean }

/** ids that would collide with better-auth core routes or other schemes */
const RESERVED_IDS = new Set(['email', 'credential', 'oauth2', 'callback', 'error', 'ok', 'api-key'])

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/

/** provider ids are autogenerated uuids (opaque, not user-facing) */
export function validProviderId(id: string) {
  return UUID_RE.test(id) && !RESERVED_IDS.has(id)
}

/** opaque provider id for new providers; the callback path is not user-facing */
export function newProviderId() {
  return uuidv7()
}

let migrated = false

export async function getOidcProviders() {
  const s = await getSettings()
  const raw = s.oidcProviders
  if (raw) {
    try {
      const parsed = JSON.parse(raw) as OidcProvider[]
      if (Array.isArray(parsed)) {
        // clientSecret must be a string: providersToPublic reads `.length` on it
        // and a legacy/corrupt row would throw instead of being dropped
        const valid = parsed.filter(p => p && p.id && p.issuer && p.clientId && typeof p.clientSecret === 'string')
        if (valid.length !== parsed.length) {
          console.error(`[oidc] dropped ${parsed.length - valid.length} invalid provider entr${parsed.length - valid.length === 1 ? 'y' : 'ies'} from stored config`)
        }
        return valid
      }
    }
    catch (e) {
      console.error('[oidc] stored provider config is corrupt:', e instanceof Error ? e.message : e)
    }
  }
  // lazy legacy migration: single provider config -> provider id 'oidc'
  if (!migrated && s.oidcIssuer && s.oidcClientId && s.oidcClientSecret) {
    const legacy: OidcProvider[] = [{ id: 'oidc', label: 'SSO', issuer: s.oidcIssuer, clientId: s.oidcClientId, clientSecret: s.oidcClientSecret }]
    await setOidcProviders(legacy)
    // the provider blob now owns the credential — clearing the legacy rows keeps
    // the secret from persisting in three places
    await setSetting('oidcIssuer', '')
    await setSetting('oidcClientId', '')
    await setSetting('oidcClientSecret', '')
    migrated = true // only after the write landed — a failure retries next call
    return legacy
  }
  return []
}

export async function setOidcProviders(list: OidcProvider[]) {
  await setSetting('oidcProviders', JSON.stringify(list))
}

export function providersToPublic(list: OidcProvider[]) {
  return list.map(({ clientSecret, ...rest }) => ({ ...rest, secretSet: (clientSecret ?? '').length > 0 }))
}
